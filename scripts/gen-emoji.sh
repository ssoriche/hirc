#!/usr/bin/env bash
# Makes crates/hirc-core/data/emoji.tsv from iamcal/emoji-data (MIT): the
# shortcodes Slack uses. One row per emoji, in emoji-data's sort order:
#   <emoji>\t<name>[,<name>...]\t<s if skin tones go after its first code point>
# The skin-tone-N modifiers are left out: emoji.rs applies them itself.
set -euo pipefail
VERSION=15.1.2
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSL "https://raw.githubusercontent.com/iamcal/emoji-data/v${VERSION}/emoji.json" -o "$tmp/emoji.json"
python3 -I - "$tmp/emoji.json" "$root/crates/hirc-core/data/emoji.tsv" <<'EOF2'
import json, sys
src, dst = sys.argv[1], sys.argv[2]
def chars(u):
    return "".join(chr(int(c, 16)) for c in u.split("-"))
def toned(base, tone):
    # The tone goes after the first code point, which loses its FE0F.
    cps = base.split("-")
    rest = cps[1:]
    if rest and rest[0] == "FE0F":
        rest = rest[1:]
    return "-".join([cps[0], tone] + rest)
rows = []
for e in json.load(open(src)):
    names = e["short_names"]
    if any(n.startswith("skin-tone-") for n in names):
        continue
    skin = ""
    v = e.get("skin_variations") or {}
    if "1F3FB" in v and v["1F3FB"]["unified"] == toned(e["unified"], "1F3FB"):
        skin = "s"
    rows.append((e["sort_order"], chars(e["unified"]), ",".join(names), skin))
rows.sort()
with open(dst, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/gen-emoji.sh from iamcal/emoji-data (MIT, see emoji-data.LICENSE). Do not edit.\n")
    for _, emoji, names, skin in rows:
        f.write(f"{emoji}\t{names}\t{skin}\n")
EOF2
echo "wrote $(grep -vc '^#' "$root/crates/hirc-core/data/emoji.tsv") emoji"
